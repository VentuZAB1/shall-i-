"""anim/out/*.json -> anim/luau/<Name>.lua (ModuleScript source for ReplicatedStorage.CreatureClips.<Name>).

Every number in [-1, 1] is packed into 2 characters (base 92, no quote or backslash) so a quaternion
(x, y, z; w >= 0 is rebuilt) costs 6 chars. CreatureAnimator decodes it once per creature type."""
import json, os, glob

HERE = os.path.dirname(os.path.abspath(__file__))
ALPHA = "".join(chr(c) for c in range(33, 127) if chr(c) not in '"\\')
B = len(ALPHA)  # 92
LEVELS = B * B - 1


def enc(v, scale=1.0):
    v = max(-1.0, min(1.0, v / scale))
    i = round((v + 1) / 2 * LEVELS)
    return ALPHA[i // B] + ALPHA[i % B]


def pack_q(seq):
    out = []
    for k in range(0, len(seq), 4):
        x, y, z, w = seq[k:k + 4]
        if w < 0:
            x, y, z = -x, -y, -z
        out.append(enc(x) + enc(y) + enc(z))
    return "".join(out)


def lua_str(s):
    return '"' + s + '"'


os.makedirs(os.path.join(HERE, "luau"), exist_ok=True)
total = 0
for path in glob.glob(os.path.join(HERE, "out", "*.json")):
    d = json.load(open(path))
    lines = ["-- generated by SLINGSHOT Creatures/anim/to_luau.py from Blender clips. Do not edit by hand.",
             "return {", f'\tfps = {d["fps"]}, rig = "{d["rig"]}", style = "{d["style"]}",',
             f'\tref = {{bone = "{d["ref"]["bone"]}", dist = {d["ref"]["dist"]:.5f}}},', "\tclips = {"]
    for cname, c in d["clips"].items():
        offs = c["off"]
        moving_off = any(abs(v) > 1e-4 for v in offs)
        lines.append(f'\t\t{cname} = {{n = {c["n"]}, loop = {"true" if c["loop"] else "false"}, len = {c["len"]:.3f}, '
                     f'stride = {c.get("stride", 0):.4f},')
        if moving_off:
            lines.append("\t\t\toff = " + lua_str("".join(enc(v) for v in offs)) + ",")
        lines.append("\t\t\trot = {")
        for b, seq in c["rot"].items():
            lines.append(f"\t\t\t\t{b} = " + lua_str(pack_q(seq)) + ",")
        lines.append("\t\t\t},\n\t\t},")
    lines.append("\t},")
    ev = ", ".join(f'{k} = {{{", ".join(f"{a} = {b}" for a, b in v.items())}}}' for k, v in d["events"].items())
    lines.append("\tevents = {" + ev + "},")
    lines.append("}")
    src = "\n".join(lines)
    total += len(src)
    open(os.path.join(HERE, "luau", d["name"] + ".lua"), "w", encoding="utf-8").write(src)
print("modules", len(glob.glob(os.path.join(HERE, "luau", "*.lua"))), "total chars", total)
print("ALPHA", ALPHA)
