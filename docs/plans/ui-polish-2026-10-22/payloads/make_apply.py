# make_apply.py (2026-10-22 UI polish, phase 2): turns payloads/*.json into execute_luau chunks (apply_<n>.lua).
# Every string is emitted ASCII-only (\t \n \" \\ and \xNN for UTF-8 bytes) and carries its FNV-1a 32 hash computed
# here: the Luau side re-hashes before touching anything, so a slip while pasting a chunk aborts that script untouched.
# Per script: every old_string must occur exactly once (checked in order on the progressively edited text), a
# `_prePolish` backup goes to ServerStorage._Backup_UIPolish.Before (disabled, tags stripped), then UpdateSourceAsync.
import json, os, glob

HERE = os.path.dirname(os.path.abspath(__file__))
ORDER = ["BrickUI", "MenuController", "StreakClient", "PlaytimeClient", "ShopClientLegacy", "IndexClientLegacy",
         "RebirthClientLegacy", "UpgradeClientLegacy", "FreeGiftClientLegacy", "FreeGiftServer", "OfflineClientLegacy",
         "StarterPackClient", "StarterPackHud"]
CHUNKS = [["BrickUI", "MenuController"], ["StreakClient", "PlaytimeClient", "ShopClientLegacy"],
          ["IndexClientLegacy", "RebirthClientLegacy", "UpgradeClientLegacy"],
          ["FreeGiftClientLegacy", "FreeGiftServer", "OfflineClientLegacy"], ["StarterPackClient", "StarterPackHud"]]

def fnv(b: bytes) -> int:
    h = 2166136261
    for x in b:
        h ^= x
        h = ((h % 256) * 16777216 + h * 403) % 4294967296
    return h

def lua_str(s: str) -> str:
    out = []
    for x in s.encode("utf-8"):
        c = chr(x)
        if c == "\\": out.append("\\\\")
        elif c == '"': out.append('\\"')
        elif c == "\n": out.append("\\n")
        elif c == "\t": out.append("\\t")
        elif 32 <= x < 127: out.append(c)
        else: out.append("\\x%02X" % x)
    return '"' + "".join(out) + '"'

PRELUDE = r'''local SSS = game:GetService("ScriptEditorService")
local CS = game:GetService("CollectionService")
local SS = game:GetService("ServerStorage")
local function fnv(s) local h = 2166136261 for i = 1, #s do h = bit32.bxor(h, string.byte(s, i)) h = ((h % 256) * 16777216 + h * 403) % 4294967296 end return h end
local function resolve(path) local o = game for part in path:gmatch("[^%.]+") do if part ~= "game" then o = o and o:FindFirstChild(part) end end return o end
local root = SS:FindFirstChild("_Backup_UIPolish") or Instance.new("Folder") root.Name = "_Backup_UIPolish" root.Parent = SS
local before = root:FindFirstChild("Before") or Instance.new("Folder") before.Name = "Before" before.Parent = root
local function count(hay, n) local c, i = 0, 1 while true do local a, b = string.find(hay, n, i, true) if not a then return c end c += 1 i = b + 1 end end
local function strip(o) for _, t in CS:GetTags(o) do CS:RemoveTag(o, t) end if o:IsA("BaseScript") then o.Enabled = false end end
local out = {}
local function apply(path, E)
	local s = resolve(path)
	if not s then table.insert(out, path .. ": MISSING") return end
	for k, e in E do if fnv(e[1]) ~= e[3] or fnv(e[2]) ~= e[4] then table.insert(out, path .. ": HASH MISMATCH edit " .. k) return end end
	local src = s.Source
	for k, e in E do
		local c = count(src, e[1])
		if c ~= 1 then table.insert(out, path .. ": old " .. k .. " count " .. c .. " (nothing applied)") return end
		local a, b = string.find(src, e[1], 1, true)
		src = string.sub(src, 1, a - 1) .. e[2] .. string.sub(src, b + 1)
	end
	local bn = s.Name .. "_prePolish"
	if not before:FindFirstChild(bn) then
		local c = s:Clone() c.Name = bn strip(c) for _, d in c:GetDescendants() do strip(d) end c.Parent = before
	end
	local ok, err = pcall(function() SSS:UpdateSourceAsync(s, function() return src end) end)
	table.insert(out, path .. (ok and (": OK " .. #E .. " edits, fnv " .. fnv(s.Source) .. (s.Source == src and "" or " SOURCE DIFFERS")) or (": UPDATE FAILED " .. tostring(err))))
end
'''

def build(src_dir, chunks, prefix):
    pay = {}
    for fn in glob.glob(os.path.join(src_dir, "*.json")):
        d = json.load(open(fn, encoding="utf-8"))
        pay[d["file_path"].split(".")[-1]] = d
    
    for n, names in enumerate(chunks, 1):
        lines = [f"-- {prefix}_{n}.lua (2026-10-22 UI polish, generated by make_apply.py): " + ", ".join(names), PRELUDE]
        for name in names:
            d = pay[name]
            lines.append(f'apply("{d["file_path"]}", {{')
            for e in d["edits"]:
                o, w = e["old_string"], e["new_string"]
                lines.append(f'\t{{{lua_str(o)}, {lua_str(w)}, {fnv(o.encode("utf-8"))}, {fnv(w.encode("utf-8"))}}},')
            lines.append("})")
        lines.append('return table.concat(out, "\\n")')
        txt = "\n".join(lines) + "\n"
        with open(os.path.join(HERE, f"{prefix}_{n}.lua"), "w", encoding="ascii", newline="\n") as f:
            f.write(txt)
        print(f"{prefix}_{n}.lua", len(txt), "bytes", names)


if __name__ == "__main__":
    build(HERE, CHUNKS, "apply")
